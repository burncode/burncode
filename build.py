def console_safe(value, stream=None):
    """Replace unsupported glyphs when Windows console uses GBK/cp936."""
    stream = stream or sys.stdout
    encoding = getattr(stream, 'encoding', None) or 'utf-8'
    return str(value).encode(encoding, errors='replace').decode(encoding, errors='replace')


def console_print(value='', stream=None):
    stream = stream or sys.stdout
    print(console_safe(value, stream), file=stream)


def pretty_report(cfg,states,check=False,color=True):
    use_color=color and sys.stdout.isatty() and not os.environ.get('NO_COLOR')
    def tint(value,code):return f'\033[{code}m{value}\033[0m' if use_color else value
    console_print('')
    console_print('  '+tint('◆ burncode','1;36')+'  '+tint('profile engine v11.8','2'))
    console_print('  '+tint('─'*54,'2'))
    console_print(f'  Profile     {cfg["profile"]["username"]}')
    console_print(f'  Themes      {cfg["themes"]["light"]} [L]  /  {cfg["themes"]["dark"]} [D]')
    console_print(f'  Language    {cfg["i18n"]["locale"]}')
    console_print(f'  Components  {", ".join(x["type"] for x in cfg["layout"] if x.get("enabled",True))}')
    console_print(f'  Projects    {len(cfg["projects"])}  ·  Social links {len(cfg.get("social",[]))}')
    console_print(f'  GitHub data {sum(p.get("_metrics_source")=="github-cache" for p in cfg["projects"])} cached projects')
    if check: console_print('  Light theme:  '+cfg['themes']['light'])
    if check: console_print('  Dark theme:   '+cfg['themes']['dark'])
    console_print('  '+tint('─'*54,'2'))
    for item in states:
        status=item['status']
        mark='✓' if status=='UNCHANGED' else '+' if status=='CREATE' else '↻'
        console_print(f'  {tint(mark,"32" if status=="UNCHANGED" else "36")}  {item["path"]:<37} {tint(status.lower(),"2")}')
    changed=sum(x['status']!='UNCHANGED' for x in states)
    console_print('  '+tint('─'*54,'2'))
    console_print('  '+tint('✓ Configuration valid' if check else '✓ Build complete','1;32')+f'  ·  {changed} changed / {len(states)-changed} unchanged')
    console_print('  Tip: python build.py --preview  (view SVG in a browser)')
    console_print('')


