def render(cfg,theme_name):
    theme=load_theme(theme_name,cfg.get('colors',{}).get(theme_name,{}))
    canvas=Canvas(theme,width=900 if cfg.get('layout_mode')=='github' else 1100)
    canvas.density = cfg.get('layout_mode','showcase')
    y=0
    for component in cfg['layout']:
        if component['type']=='social':continue  # Social exists only as individually clickable README links.
        if component.get('enabled',True) and (component['type'] not in ('languages','github_stats','currently_building','development_focus','recent_releases','blog') or cfg.get('widgets',{}).get(component['type'],{}).get('enabled',False)):
            renderer=(
                {'hero':compact.hero,'projects':compact.project_list,'activity':compact.activity,'footer':compact.footer}.get(component['type'])
                if cfg.get('layout_mode')=='github' else None
            ) or COMPONENTS[component['type']]
            h=renderer(canvas,cfg,y,component.get('options',{}))
            if not isinstance(h,(int,float)) or h<=0:raise ConfigError(f'Invalid height from {component["type"]}')
            y+=h+8
    height=max(1,y-8)
    canvas.rect(0,0,canvas.width-1,height-1,stroke=theme['colors']['border'])
    return svg_document(canvas,height,f'{cfg["profile"]["username"]} developer profile, {theme_name} theme')


def render_sections(cfg,theme_name):
    """Render individually linkable SVG sections from the same showcase scene.

    Each strip retains the full original scene, clipped via viewBox.  The
    experimental README is intentionally separate from the default README.
    """
    import re
    theme=load_theme(theme_name,cfg.get('colors',{}).get(theme_name,{}))
    canvas=Canvas(theme,width=1100);canvas.density='showcase'
    y=0;sections=[];content_bounds={}
    for component in cfg['layout']:
        if not component.get('enabled',True):continue
        kind=component['type']
        if kind in ('languages','github_stats','currently_building','development_focus','recent_releases','blog') and not cfg.get('widgets',{}).get(kind,{}).get('enabled',False):continue
        if kind=='social':
            for i,entry in enumerate(cfg.get('social',[])):
                sections.append((f'connect-{i+1}',-1,38,entry['url']))
            continue
        start=y
        opts={**component.get('options',{})}
        h=COMPONENTS[kind](canvas,cfg,y,opts)
        if kind=='projects':
            sections.append(('projects-heading',start,42,None))
            row_h=max(96,int(load_theme(theme_name)['components'].get('projects',{}).get('row_height',86)))
            for i,project in enumerate(cfg['projects']):
                sections.append((f'project-{i+1}',start+42+i*row_h,row_h,project.get('url')))
        elif kind=='blog' and cfg.get('_blog_posts',cfg.get('widgets',{}).get('blog',{}).get('posts')):
            sections.append(('blog-heading',start,51,None))
            for i,post in enumerate(cfg.get('_blog_posts',cfg['widgets']['blog']['posts'])):
                sections.append((f'blog-{i+1}',start+51+i*36,36,post['url']))
        elif kind=='recent_releases' and cfg.get('_releases'):
            sections.append(('releases-heading',start,57,None))
            for i,release in enumerate(cfg['_releases']):
                sections.append((f'release-{i+1}',start+57+i*35,35,release.get('url') or None))
        else:sections.append((kind,start,h,None))
        # Keep scene coordinates separated for safe clipping, but export only
        # actual component content. GitHub already adds an inline-image line box.
        label, top, section_height, link = sections[-1]
        content_bounds[label]=(top,section_height)
        y += h + 8

    height=max(1,y-8)
    original=svg_document(canvas,height,f'{cfg["profile"]["username"]} profile')
    inner=original[original.index('<svg '):]
    inner=inner[inner.index('>')+1:inner.rindex('</svg>')]
    # Reuse full coordinate space for consistent backgrounds and borders.
    files={}
    for name,top,h,url in sections:
        if name.startswith('connect-'):
            index=int(name.split('-')[1])-1
            entry=cfg['social'][index]
            label=html.escape(entry['label'])
            fg=theme['colors']['foreground'];bd=theme['colors']['border'];bg=theme['colors']['background'];accent=theme['colors']['accent']
            icon=entry.get('icon','link');display=entry.get('display','both')
            from profilegen.icons.brands import mark
            from profilegen.text import width as text_width
            label=entry['label']
            shown=label if display!='icon' else ''
            button_w=max(45,min(240,int(text_width(shown,13.2)+ (51 if display=='both' else 26 if display=='text' else 0))))
            if display=='icon':button_w=43
            icon_svg=mark(icon,12,10,fg,18) if display!='text' else ''
            text_x=39 if display=='both' else 13
            label_svg=f'<text x="{text_x}" y="24" font-family="Consolas,monospace" font-size="13.2" fill="{fg}">{html.escape(shown)}</text>' if shown else ''
            svg=(f'<svg xmlns="http://www.w3.org/2000/svg" width="{button_w}" height="38" viewBox="0 0 {button_w} 38" role="img" aria-label="{html.escape(entry["label"],quote=True)}">'
                 f'<rect x="1" y="1" width="{button_w-2}" height="36" rx="3" fill="{bg}" stroke="{bd}"/>'
                 +icon_svg+label_svg+'</svg>')
            files[name]=(svg,url)
            continue
        if name.startswith('gap-'):
            # Explicit transparent SVG: preserves original separation on GitHub
            # even when Markdown/HTML styles are sanitized.
            files[name]=(f'<svg xmlns="http://www.w3.org/2000/svg" width="1100" height="{h}" viewBox="0 0 1100 {h}" aria-hidden="true"></svg>\n',None)
            continue
        header=f'<svg xmlns="http://www.w3.org/2000/svg" width="1100" height="{h}" viewBox="0 {top} 1100 {h}" role="img" aria-label="{html.escape(name,quote=True)}">'
        # Keep the gap blank: the next component's top stroke otherwise bleeds
        # into this viewport because all strips share the complete scene.
        clip_top,clip_height=content_bounds.get(name,(top,h))
        clip=(f'<defs><clipPath id="section-clip"><rect x="0" y="{clip_top}" width="1100" height="{clip_height+0.5}"/></clipPath></defs>')
        files[name]=(f'<!-- {MARKER} v12.9 sections -->\n'+header+clip+'<g clip-path="url(#section-clip)">'+inner+'</g></svg>\n',url)
    return files


def make_readme(cfg):
    t=cfg['themes'];out=[f'<!-- {MARKER} v12.9; edit config.json then run python build.py -->']
    light=render_sections(cfg,t['light'])
    dark=render_sections(cfg,t['dark'])
    connect_markup=[]
    def _social_width(cfg,name):
        from profilegen.text import width as text_width
        entry=cfg['social'][int(name.split('-')[1])-1]
        mode=entry.get('display','both')
        if mode=='icon':return 43
        return max(45,min(240,int(text_width(entry['label'],13.2)+(51 if mode=='both' else 26))))
    for name,(svg,url) in light.items():
        source=f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/sections/{t["dark"]}/{name}.svg"><img src="assets/sections/{t["light"]}/{name}.svg" alt="{html.escape(name,quote=True)}" width="100%"></picture>'
        if url:
            label=next((p.get('name','') for i,p in enumerate(cfg['projects']) if name==f'project-{i+1}'),'')
            hint=(f'Open repository: {label}' if label else next((f'Open {e["label"]}' for i,e in enumerate(cfg.get('social',[])) if name==f'connect-{i+1}'), next((f'Open article: {post["title"]}' for i,post in enumerate(cfg.get('_blog_posts',cfg.get('widgets',{}).get('blog',{}).get('posts',[]))) if name==f'blog-{i+1}'),'Open link')))
            source=f'<a href="{html.escape(url,quote=True)}" target="_blank" rel="noopener noreferrer" title="{html.escape(hint,quote=True)}" aria-label="{html.escape(hint,quote=True)}">{source}</a>'
        if name.startswith('connect-'):
            source=source.replace('width="100%"',f'width="{_social_width(cfg,name)}"')
            connect_markup.append(source)
        else:
            # Native HTML alignment survives sanitization and avoids the inline
            # image's descender gap without relying on custom README CSS.
            source=source.replace('width="100%"','width="100%" align="top"')
            # Flush the social toolbar before ANY following section, including gaps.
            # Otherwise CSS/transparent spacer strips can make it appear anchored elsewhere.
            if connect_markup:
                out.append('<p class="social-toolbar" align="center">'+' &nbsp; '.join(connect_markup)+'</p>')
                connect_markup=[]
            out.append('<div>'+source+'</div>')
    if connect_markup:
        out.append('<p class="social-toolbar" align="center">'+' &nbsp; '.join(connect_markup)+'</p>')
    return '\n'.join(out)+'\n'


def make_preview_html(cfg):
    """v12.5-style responsive light/dark matrix using the real clickable README."""
    markup = make_readme(cfg)
    panels = []
    for width in (720, 900, 1100):
        for mode, theme in (('Light', cfg['themes']['light']), ('Dark', cfg['themes']['dark'])):
            # The README picture elements select by OS color scheme; preview
            # explicitly pins the chosen theme so both variants can be compared.
            content = re.sub(r'<picture>\s*<source[^>]*>\s*<img\s+src="assets/sections/[^/]+/([^"]+)"',
                             lambda m: '<img src="assets/sections/'+theme+'/'+m.group(1)+'"', markup)
            content = content.replace('</picture>', '')
            # Single-image links and social images are also theme-pinned.
            content = re.sub(r'assets/sections/(?:'+re.escape(cfg['themes']['light'])+'|'+re.escape(cfg['themes']['dark'])+')/',
                             'assets/sections/'+theme+'/', content)
            panels.append(f'<section class="panel" style="max-width:{width}px"><h2>{mode} · {html.escape(theme)} · {width}px</h2><div class="readme" style="background:{load_theme(theme)['colors']['background']}">{content}</div></section>')
    return ("<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
            "<title>GitHub README · Width & Theme Preview</title><style>"
            "body{margin:0;padding:20px;background:#e8e9eb;color:#17191c;font:14px system-ui}"
            "section.panel{margin:0 auto 30px}h2{font-size:14px;font-weight:600;margin:0 0 12px}"
            ".readme{background:#fff;padding:8px;overflow:hidden;font-size:16px;line-height:1.5}"
            ".readme img{max-width:100%;height:auto;border:0}"
            ".readme>div img{display:inline;width:100%}.readme p.social-toolbar{margin:5px 0 9px;line-height:40px;text-align:center}"
            ".readme p.social-toolbar img{display:inline-block;width:auto!important;max-width:none;vertical-align:middle}"
            ".readme a{cursor:pointer}.readme a:hover img{filter:brightness(.985)}"
            "@media(prefers-color-scheme:dark){body{background:#191b20;color:#eee}}"
            "</style></head><body>"+''.join(panels)+"</body></html>\n")

def safe_to_replace(path,force=False):
    if not path.exists() or force:return
    try:
        if MARKER in path.read_text(encoding='utf-8')[:300]:return
    except UnicodeDecodeError:pass
    raise ConfigError(f'Refusing to overwrite user-maintained file: {path} (use --force intentionally)')


def plan_files(cfg, root):
    root = Path(root)
    targets = {root / 'README.md': make_readme(cfg)}
    for theme_name in {cfg['themes']['light'], cfg['themes']['dark']}:
        for name,(svg,url) in render_sections(cfg,theme_name).items():
            # Every generated SVG, including social and gap strips, carries ownership marker.
            if MARKER not in svg[:300]:
                svg = f'<!-- {MARKER} v12.7 -->\n' + svg
            targets[root / 'assets' / 'sections' / theme_name / f'{name}.svg'] = svg
    return targets


def file_state(path, data):
    if not path.exists():
        return 'CREATE'
    try:
        return 'UNCHANGED' if path.read_text(encoding='utf-8') == data else 'UPDATE'
    except (OSError, UnicodeDecodeError):
        return 'UPDATE'


def build(cfg, root, force=False):
    root = Path(root)
    targets = plan_files(cfg, root)
    for path, data in targets.items():
        if file_state(path, data) != 'UNCHANGED':
            safe_to_replace(path, force)
    studio = cfg.get('_studio_path')
    if studio:
        target = root / 'assets' / f'studio{studio.suffix.lower()}'
        if studio != target.resolve() and target.exists() and not force and target.read_bytes() != studio.read_bytes():
            raise ConfigError(f'Image already exists: {target} (use --force intentionally)')
    (root / 'assets').mkdir(parents=True, exist_ok=True)
    for path in targets: path.parent.mkdir(parents=True,exist_ok=True)
    if studio:
        target = root / 'assets' / f'studio{studio.suffix.lower()}'
        if studio != target.resolve() and (not target.exists() or target.read_bytes() != studio.read_bytes()):
            target.write_bytes(studio.read_bytes())
    results = []
    for path, data in targets.items():
        state = file_state(path, data)
        if state != 'UNCHANGED':
            tmp = path.with_name(path.name + '.tmp')
            tmp.write_text(data, encoding='utf-8')
            tmp.replace(path)
        results.append((path, state))
    return results


