def read_json(path):
    try:
        data=json.loads(path.read_text(encoding='utf-8'))
    except (OSError, json.JSONDecodeError) as exc:
        raise ConfigError(f'Cannot read JSON {path}: {exc}') from exc
    if not isinstance(data,dict):
        raise ConfigError(f'{path}: JSON root must be an object')
    return data


def theme_names():
    return sorted(p.stem for p in THEMES_DIR.glob('*.json'))


def load_theme(name, overrides=None):
    if not re.fullmatch(r'[a-zA-Z0-9_-]+',name):
        raise ConfigError(f'Invalid theme name: {name}')
    path=THEMES_DIR / f'{name}.json'
    if not path.is_file():
        raise ConfigError(f'Unknown theme {name!r}; available: {", ".join(theme_names())}')
    t=read_json(path)
    for section in ('colors','fonts','typography','style'):
        if not isinstance(t.get(section),dict):
            raise ConfigError(f'{path.name}: {section} must be an object')
    for key in COLOR_KEYS:
        color=t['colors'].get(key)
        if not isinstance(color,str) or not HEX.fullmatch(color):
            raise ConfigError(f'{path.name}: invalid colors.{key}')
    for key in ('body','heading'):
        font=t['fonts'].get(key)
        if not isinstance(font,str) or not font.strip() or len(font)>160 or any(ch in font for ch in '<>&"'):
            raise ConfigError(f'{path.name}: invalid fonts.{key}')
    for section,keys in [('typography',('title_size','body_size','line_height')),('style',('border_width','corner_radius','pixel_density'))]:
        for key in keys:
            val=t[section].get(key)
            if not isinstance(val,(int,float)) or isinstance(val,bool) or not 0<=val<=120:
                raise ConfigError(f'{path.name}: invalid {section}.{key}')
    # Theme component overrides: validated to avoid malformed or unsafe SVG output.
    components=t.get('components',{})
    if not isinstance(components,dict):raise ConfigError(f'{name}: components must be an object')
    for component,settings in components.items():
        if component not in ('hero','projects','activity','footer') or not isinstance(settings,dict):
            raise ConfigError(f'{name}: invalid component style {component}')
        for key,value in settings.items():
            if key in ('icon_size','chip_font_size','chip_height','row_height','stat_font_size'):
                if type(value) is not int or not 6<=value<=150:raise ConfigError(f'{name}: invalid {component}.{key}')
            elif key in ('chip_border','empty_color','active_color','divider_color','stat_border','stat_background'):
                if not isinstance(value,str) or not HEX.fullmatch(value):raise ConfigError(f'{name}: invalid {component}.{key}')
            elif key=='studio_scale':
                if not isinstance(value,(int,float)) or isinstance(value,bool) or not 0.75<=value<=1.0:raise ConfigError(f'{name}: invalid studio_scale')
            elif key=='variant':
                if component!='hero' or value not in ('classic','compact','editorial'):raise ConfigError(f'{name}: invalid hero variant')
            elif key=='icon_variant':
                if value not in ('outline','solid','terminal','retro','soft'):raise ConfigError(f'{name}: invalid icon variant')
            elif key!='stats_variant':
                raise ConfigError(f'{name}: unknown {component}.{key}')
    icons=t.get('icons',{}).get('projects',[])
    if not isinstance(icons,list) or any(x not in ('cube','book','heritage','code','terminal','star') for x in icons):
        raise ConfigError(f'{name}: icons.projects must contain supported icon names')
    for key,color in (overrides or {}).items():
        if key not in COLOR_KEYS or not isinstance(color,str) or not HEX.fullmatch(color):
            raise ConfigError(f'colors.{name}.{key}: expected #RRGGBB')
        t['colors'][key]=color
    studio=t.get('studio', {})
    if not isinstance(studio,dict) or studio.get('scene','night_city') not in SCENES:
        raise ConfigError(f'{path.name}: studio.scene must be one of {SCENES}')
    return t


def check_text(value,field,max_length=400):
    if not isinstance(value,str) or not value.strip() or len(value)>max_length or any(ord(ch)<32 for ch in value):
        raise ConfigError(f'{field} must be nonempty text (up to {max_length} chars)')
    return value.strip()


def check_list(value,field,max_items=10,max_length=70):
    if not isinstance(value,list) or len(value)>max_items:
        raise ConfigError(f'{field} must be a list of at most {max_items} items')
    return [check_text(item,f'{field}[{i}]',max_length) for i,item in enumerate(value)]


