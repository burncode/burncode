"""Escaped SVG primitives and shared rendering context."""
from html import escape
from .text import ellipsize, wrap


class Canvas:
    def __init__(self, theme, width=1100):
        self.theme = theme
        self.width = width
        self.parts = []
        self.c = theme['colors']
        self.fonts = theme['fonts']
        self.style = theme['style']
        self.density = 'showcase'

    def raw(self, content):
        self.parts.append(content)

    def rect(self, x, y, w, h, fill='none', stroke=None, radius=None):
        attr = f' stroke="{escape(stroke)}" stroke-width="{self.style["border_width"]}"' if stroke else ''
        r = self.style['corner_radius'] if radius is None else radius
        self.raw(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{escape(fill)}"{attr}/>')

    def line(self, x, y, x2, y2, color=None):
        self.raw(f'<path d="M{x} {y} L{x2} {y2}" stroke="{escape(color or self.c["border"])}"/>')

    def text(self, x, y, value, size=14, color=None, bold=False, max_width=None, family='body', anchor=None):
        if self.density == 'showcase' and size <= 15:
            size = round(size * (1.20 if size <= 12 else 1.10), 1)
        if self.density == 'github' and size <= 15:
            size = round(size * (1.12 if size >= 12 else 1.05), 1)
        s = str(value)
        if max_width is not None:
            s = ellipsize(s, max_width, size)
        font = escape(self.fonts[family], quote=True)
        anchor_attr = f' text-anchor="{anchor}"' if anchor else ''
        self.raw(f'<text x="{x}" y="{y}" font-family="{font}" font-size="{size}" fill="{escape(color or self.c["foreground"])}"'+(' font-weight="700"' if bold else '')+anchor_attr+f'>{escape(s)}</text>')

    def multiline(self, x, y, value, max_width, size=14, max_lines=2, step=19, color=None):
        lines = wrap(value, max_width, size, max_lines)
        for i, line in enumerate(lines):
            self.text(x, y+i*step, line, size, color)
        return len(lines)


def svg_document(canvas, height, label):
    c = canvas.c
    opening = f'<svg xmlns="http://www.w3.org/2000/svg" width="{canvas.width}" height="{height}" viewBox="0 0 {canvas.width} {height}" role="img" aria-label="{escape(label, quote=True)}">'
    background = f'<rect width="{canvas.width}" height="{height}" fill="{c["background"]}"/>'
    return '<!-- Generated by burncode Hacker Profile Generator v12.3 -->\n' + opening + background + ''.join(canvas.parts) + '</svg>\n'
